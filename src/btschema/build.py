"""Build versioned JSON Schema and Python vocabulary artifacts."""

import argparse
import json
import re
from pathlib import Path

from jsonschema import Draft202012Validator

from .build_utils import (
    LICENSE_PATH,
    SCHEMA_PATH,
    license_enum,
    license_ids,
    read_json,
    repository_root,
    schema_license_ids,
)


# Paths relative to the single tool's properties. Variable names are the
# public names used by consumers of the generated Python module.
VOCABS = {
    "LANGUAGE": "language.items.enum",
    "LICENSE": "license.enum",
    "OPERATING_SYSTEM": "operatingSystem.items.enum",
    "TOOL_TYPE": "toolType.items.enum",
    "MATURITY": "maturity.enum",
    "COST": "cost.enum",
    "ACCESSIBILITY": "accessibility.enum",
    "ELIXIR_PLATFORM": "elixirPlatform.items.enum",
    "ELIXIR_COMMUNITY": "elixirCommunity.items.enum",
    "ELIXIR_NODE": "elixirNode.items.enum",
    "OTHER_ID_TYPE": "otherID.items.properties.type.enum",
    "LINK_TYPE": "link.items.properties.type.items.enum",
    "DOWNLOAD_TYPE": "download.items.properties.type.enum",
    "DOCUMENTATION_TYPE": "documentation.items.properties.type.items.enum",
    "RELATION_TYPE": "relation.items.properties.type.enum",
    "PUBLICATION_TYPE": "publication.items.properties.type.items.enum",
    "CREDIT_TYPE_ENTITY": "credit.items.properties.typeEntity.enum",
    "CREDIT_TYPE_ROLE": "credit.items.properties.typeRole.items.enum",
}


def output_path(root, output_dir, filename):
    directory = output_dir if output_dir is not None else root / "dist"
    directory.mkdir(parents=True, exist_ok=True)
    return directory / filename


def build_jsonschema(version, output_dir=None):
    if not re.fullmatch(r"[A-Za-z0-9][A-Za-z0-9._+-]*", version):
        raise ValueError(f"Invalid artifact version: {version!r}")
    root = repository_root()
    content = (root / SCHEMA_PATH).read_bytes()
    Draft202012Validator.check_schema(json.loads(content))
    path = output_path(root, output_dir, f"biotools-{version}.schema.json")
    path.write_bytes(content)
    return path


def generate_vocab(output_dir=None):
    root = repository_root()
    schema = read_json(root / SCHEMA_PATH)
    snapshot = read_json(root / LICENSE_PATH)
    if license_enum(schema) != schema_license_ids(snapshot):
        raise ValueError("The schema license enum and the SPDX snapshot differ. Run fetch-spdx.")

    properties = schema["$defs"]["tool"]["properties"]
    blocks = ['"""Controlled vocabularies generated by build-schema."""']
    for name, enum_path in VOCABS.items():
        values = properties
        for part in enum_path.split("."):
            values = values[part]
        if name == "LICENSE":
            values = list(dict.fromkeys([*values, *license_ids(snapshot, "deprecated")]))
        entries = "\n".join(f"    ({value!r}, {value!r})," for value in values)
        blocks.append(f"{name} = [\n{entries}\n]")

    path = output_path(root, output_dir, "biotools_vocab.py")
    path.write_text("\n\n".join(blocks) + "\n", encoding="utf-8")
    return path


def build():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--version", default="dev")
    parser.add_argument("--output-dir", type=Path)
    parser.add_argument("--only", choices=("all", "jsonschema", "vocab"), default="all")
    args = parser.parse_args()
    if args.only in ("all", "jsonschema"):
        print(build_jsonschema(args.version, args.output_dir))
    if args.only in ("all", "vocab"):
        print(generate_vocab(args.output_dir))


if __name__ == "__main__":
    build()
